"""Derive an instrument's marking apparatus from the workbook it wraps.

A workbook instrument carries three things that all say the same thing in different shapes:

  the workbook   every element has `uoc` — the items that element evidences
  the marking    guide criteria A1…An, each with a UoC-traceability line
  the reverse    map: every UoC item the AT claims, against the criterion that evidences it

Hand-maintaining the second and third is how they drift from the first. Here they are DERIVED:
an author declares which tasks each criterion groups, and this module produces the traceability
lines and the reverse map from the workbook's own tags. A tag added to a task appears in its
criterion and in the reverse map without anyone remembering to add it twice.

The verbatim UoC wording in the reverse map is read from the cluster's `consolidated_uoc.md`,
which is the source of truth the transcription and consolidation gates already prove. An item a
criterion claims that does not appear there is a phantom, and `build_reverse_map` raises rather
than printing a plausible-looking row.
"""
